def get_text(lang_code: str, key: str, **kwargs) -> str:
    lang = lang_code if lang_code in LOCALES else 'en'
    text = LOCALES[lang].get(key, LOCALES['en'].get(key, key))
    if kwargs:
        return text.format(**kwargs)
    return text
